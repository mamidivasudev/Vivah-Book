const privacyPolicyText = '''
VivahBook is a wedding gift register app for recording gifts given and received at functions.

SHORT VERSION
Everything you enter stays on your phone. We do not collect, upload, sell or share your data. The app has no internet access and asks for no permissions.

WHAT THE APP STORES ON YOUR DEVICE
• Functions you create: name, type, date and whether it is your own function.
• Entries: the name of the person, optional village or area, relationship, amount or gift note, and the date you entered it.
• Your text-size setting.
This data is saved only in the app's private storage on your phone. It is not backed up to the cloud by the app.

COPY, BACKUP AND RESTORE
The app can copy a register or a backup as text to your clipboard when you tap a button. Where you paste it (for example into a chat or a notes app) is your choice. The app does not send it anywhere. Restoring a backup replaces the data in the app with the text you paste.

WHAT WE DO NOT DO
• No accounts, no sign-in.
• No ads, no analytics, no tracking, no third-party SDKs that collect data.
• No access to your contacts, messages, location, camera, microphone, photos or files.

YOUR CONTROL
You can delete everything at any time: Settings > Delete all my data. Uninstalling the app also removes its data. Please make a backup first if you want to keep your records.

OTHER PEOPLE'S INFORMATION
Entries contain names of other people. They stay on your device and are used only to show your own register.

CHANGES
If this policy changes, the updated version will be shown in the app and on the store listing.
''';

